#include "nsc_image_guard.hpp"
extern "C" {
#include "nsc_sha256.h"
}

namespace nsc::image {
Profile Identify(const void* text, std::size_t mapped_size) {
    if (!text || mapped_size < kTextSize) return Profile::Unsupported;
    static constexpr unsigned char stock[32] = {
        0xf6,0xec,0x83,0xda,0xd4,0x53,0x7b,0x0f,0xa5,0x3c,0xf7,0x07,0xc1,0x0f,0x48,0xa4,
        0x38,0x11,0x79,0x05,0x58,0x1e,0x2e,0xd3,0xf4,0x2c,0xf3,0xcf,0x29,0xa7,0x31,0xd7};
    static constexpr unsigned char r180[32] = {
        0xbb,0xf6,0xc6,0x2a,0xf4,0x6c,0xe0,0x8c,0x15,0xa7,0x53,0xc0,0x78,0xac,0xcb,0x2f,
        0x63,0x8a,0xd7,0x75,0xe1,0xf6,0x95,0x25,0x6e,0x45,0x2f,0x9f,0x19,0x7d,0x7d,0x21};
    SHA256_CTX ctx{};
    unsigned char digest[32];
    nsc_sha256_init(&ctx);
    nsc_sha256_update(&ctx, static_cast<const unsigned char*>(text), kTextSize);
    nsc_sha256_final(&ctx, digest);
    unsigned stock_diff = 0, r180_diff = 0;
    for (unsigned i = 0; i < 32; ++i) {
        stock_diff |= digest[i] ^ stock[i];
        r180_diff |= digest[i] ^ r180[i];
    }
    return !stock_diff ? Profile::Stock170 : !r180_diff ? Profile::R180 : Profile::Unsupported;
}
}
